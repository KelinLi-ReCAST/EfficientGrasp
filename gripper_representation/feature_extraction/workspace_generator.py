def rot_Z(ang):
    r = np.array([[np.cos(ang), -np.sin(ang)], [np.sin(ang), np.cos(ang)]])
    return r


def fin_tip_pos(lengths,ang):
    p = np.zeros(2)
    for i in range(len(lengths)):
        p = p + np.matmul(rot_Z(ang), np.array([0, lengths[i]]))
    return p
        
         
