    theta_step = theta_range/2
    for theta1 in np.arange(0, theta_range, theta_step):  # loop through five bar configurations to obtain base joint positions
        for theta2 in np.arange(0, theta_range, theta_step):
            P2 = P1+l1*np.array([np.cos(theta1), np.sin(theta1)])
            P4 = P5+l1*np.array([np.cos(theta2), np.sin(theta2)])
            d24 = np.sqrt((P4[0]-P2[0])**2+(P4[1]-P2[1])**2)
            if (d24**2+l2**2+l2**2)**2-2*(d24**4+l2**4+l2**4) < 0:
                continue
            A_243 = np.sqrt((d24**2+l2**2+l2**2)**2-2*(d24**4+l2**4+l2**4))/4
            Z_243 = (1/(2*d24**2))*np.array([[d24**2+l2**2-l2**2, -4*A_243], [4*A_243, d24**2+l2**2-l2**2]])
            p24 = P4-P2
            p23 = np.matmul(Z_243, p24)
            P3 = P2 + p23
            p54 = P5-P4
            p43 = P3-P4
            R_fg = [0]*3
            finger_bases = [P2, P3, P4]
            if fin_ori_meth == 0:  # If actuated, loop through finger orientations
                for fin_ori_count1 in range(3):
                    fg_x_ax1 = np.append(np.matmul(rot_Z(-np.pi/2-fin_ori_count1*fin_ori_step), p23/np.linalg.norm(p23)), 0)
                    fg_z_ax1 = np.array([0, 0, 1])
                    fg_y_ax1 = np.cross(fg_z_ax1, fg_x_ax1)
                    R_fg[0] = np.column_stack((fg_x_ax1, fg_y_ax1, fg_z_ax1))
                    for fin_ori_count2 in range(3):
                        fg_x_ax2 = np.append(np.matmul(rot_Z(np.pi/2+fin_ori_count2*fin_ori_step), p54/np.linalg.norm(p54)), 0)
                        fg_z_ax2 = np.array([0, 0, 1])
                        fg_y_ax2 = np.cross(fg_z_ax2, fg_x_ax2)
                        R_fg[1] = np.column_stack((fg_x_ax2, fg_y_ax2, fg_z_ax2))
                        for fin_ori_count3 in range(3):
                            fg_x_ax3 = np.append(np.matmul(rot_Z(np.pi/2+fin_ori_count3*fin_ori_step), p43/np.linalg.norm(p43)), 0)
                            fg_z_ax3 = np.array([0, 0, 1])
                            fg_y_ax3 = np.cross(fg_z_ax3, fg_x_ax3)
                            R_fg[2] = np.column_stack((fg_x_ax3, fg_y_ax3, fg_z_ax3))
                            workspace = np.vstack([workspace, finger_bend(actu_meth, phal_lengths, R_fg, finger_bases)])
            else:  # If passively/spring-driven, compute finger orientations
                C = (P2+P3+P4)/3
                fg_x_ax1 = np.append((C-P2)/np.linalg.norm(C-P2), 0)
                fg_z_ax1 = np.array([0, 0, 1])
                fg_y_ax1 = np.cross(fg_z_ax1, fg_x_ax1)
                R_fg[0] = np.column_stack((fg_x_ax1, fg_y_ax1, fg_z_ax1))
                fg_x_ax2 = np.append((C-P3)/np.linalg.norm(C-P3), 0)
                fg_z_ax2 = np.array([0, 0, 1])
                fg_y_ax2 = np.cross(fg_z_ax2, fg_x_ax2)
                R_fg[1] = np.column_stack((fg_x_ax2, fg_y_ax2, fg_z_ax2))
                fg_x_ax3 = np.append((C-P4)/np.linalg.norm(C-P4), 0)
                fg_z_ax3 = np.array([0, 0, 1])
                fg_y_ax3 = np.cross(fg_z_ax3, fg_x_ax3)
                R_fg[2] = np.column_stack((fg_x_ax3, fg_y_ax3, fg_z_ax3))
                workspace = np.vstack([workspace, finger_bend(actu_meth, phal_lengths, R_fg, finger_bases, mult=27)])
    return workspace


