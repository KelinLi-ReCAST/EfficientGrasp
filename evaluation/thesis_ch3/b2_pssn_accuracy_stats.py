#!/usr/bin/env python3
"""B2: inventory of (a) the one locally available UniGrasp label directory
data/objects/1812, (b) results/pssn_accuracy/*.npy|*.mat, (c) inference of the
test-set denominator N from the quantisation of the accuracy values, and (d)
matching of the thesis Table 3.2 cells against rows of the stored curves.

Usage: python3 evaluation/thesis_ch3/b2_pssn_accuracy_stats.py
Writes results/thesis_ch3/B2_pssn_accuracy_dump.md
"""
import os, re, glob, collections
import numpy as np
import scipy.io as sio

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OBJ_DIR = os.path.join(ROOT, 'contact_point_selection', 'UniGrasp', 'data', 'objects', '1812')
ACC_DIR = os.path.join(ROOT, 'results', 'pssn_accuracy')
OUT = os.path.join(ROOT, 'results', 'thesis_ch3', 'B2_pssn_accuracy_dump.md')

# Thesis Table 3.2 (Top-1, Top-10) in percent
TABLE = collections.OrderedDict([
    ('E Robotiq-3F', [(99.3, 100), (97.5, 98.9), (88.7, 96.1)]),
    ('U Robotiq-3F', [(91.9, 99.6), (83.4, 90.8), (76.0, 86.2)]),
    ('E Kinova-3F', [(97.9, 100), (87.6, 97.2), (75.6, 89.8)]),
    ('U Kinova-3F', [(86.9, 98.2), (66.4, 80.2), (54.8, 70.7)]),
    ('E BarrettHand', [(100, 100), (96.5, 99.7), (91.9, 96.5)]),
    ('U BarrettHand', [(94.3, 98.9), (86.9, 91.5), (77.7, 87.6)]),
    ('I BarrettHand', [(92.2, 98.6), (85.9, 90.8), (77.4, 86.9)]),
])

L = []
def p(s=''):
    L.append(s)

p('# B2 dump: local UniGrasp label files and results/pssn_accuracy')
p()
p('Generated by `python3 evaluation/thesis_ch3/b2_pssn_accuracy_stats.py`')
p()

# ---------------------------------------------------------------- (a) objects/1812
p('## (a) contact_point_selection/UniGrasp/data/objects/1812 (the only object directory present locally)')
p()
files = sorted(os.listdir(OBJ_DIR))
p('%d files. Prefix of the long file names: `%s`' % (len(files), files[-1].split('_pcn')[0][:60] + '...'))
p()
p('| file suffix / name | size (bytes) | loaded type | shape / keys | notes |')
p('|---|---|---|---|---|')
for f in files:
    path = os.path.join(OBJ_DIR, f)
    sz = os.path.getsize(path)
    short = re.sub(r'^812_rho.*?_zdim0\.0749960+', '<obj>', f)
    desc, kind, note = '', '', ''
    try:
        if f.endswith('.npy'):
            a = np.load(path, allow_pickle=True)
            kind = 'ndarray'
            desc = '%s %s' % (a.shape, a.dtype)
            if a.dtype != object and a.size:
                if a.ndim == 1 and a.size <= 2048 and set(np.unique(a)).issubset({0, 1}):
                    note = 'binary; positives=%d' % int(a.sum())
                elif a.ndim == 2 and a.shape == (2048, 2048):
                    note = 'nonzero=%d; symmetric=%s; max=%.3g' % (np.count_nonzero(a), np.array_equal(a, a.T), a.max())
                elif a.ndim == 3:
                    note = 'nonzero=%d; max=%.3g' % (np.count_nonzero(a), a.max())
                elif a.ndim == 1:
                    note = 'min=%s max=%s' % (a.min(), a.max())
                elif a.ndim == 2:
                    note = 'min=%.4g max=%.4g' % (a.min(), a.max())
        elif f.endswith('.npz'):
            z = np.load(path, allow_pickle=True)
            kind = 'npz'
            desc = '; '.join('%s: %s %s' % (k, z[k].shape, z[k].dtype) for k in z.files)
            if 'par' in z.files and z['par'].ndim == 3 and z['par'].shape[1] > 5:
                par = z['par']
                note = 'par[:,5,1:3] contact idx range %d..%d' % (par[:, 5, 1:3].min(), par[:, 5, 1:3].max())
        elif f.endswith('.txt'):
            kind = 'text'
            desc = open(path).read().strip().replace('\n', ' / ')[:120]
        elif f.endswith('.pgm'):
            kind = 'pgm'
            with open(path, 'rb') as fh:
                desc = ' '.join(fh.readline().strip().decode('latin1') for _ in range(3))
    except Exception as e:  # noqa
        kind = 'ERR'; desc = str(e)[:80]
    p('| %s | %d | %s | %s | %s |' % (short, sz, kind, desc, note))
p()

# ---------------------------------------------------------------- (b) accuracy files
p('## (b) results/pssn_accuracy contents')
p()
arrays = collections.OrderedDict()
for f in sorted(glob.glob(os.path.join(ACC_DIR, '*'))):
    name = os.path.basename(f)
    if f.endswith('.npy'):
        arrays[name] = np.load(f)
        hdr = ''
    else:
        m = sio.loadmat(f)
        arrays[name] = m['acc']
        hdr = m['__header__'].decode()
    a = arrays[name]
    p('- `%s`: shape %s, dtype %s%s' % (name, a.shape, a.dtype, ('; header: ' + hdr) if hdr else ''))
p()
p('Identical arrays:')
names = list(arrays)
for i in range(len(names)):
    for j in range(i + 1, len(names)):
        a, b = arrays[names[i]], arrays[names[j]]
        if a.shape == b.shape and np.allclose(a, b):
            p('- %s == %s' % (names[i], names[j]))
p()
p('Row layout: point_set_selection_test.py `__main__` (commented block, lines 1233-1239) evaluates `restore_stage3(i+1)` for i in range(220) if i%3==0 -> 74 checkpoints (epochs 1,4,...,220); each row = (Top-1, Top-10) for ONE gripper (`gripper_index = np.array([12])` at line 539 of the preserved snapshot).')
p()
p('Per-file summary (values in %):')
p()
p('| file | rows | Top-1 max (row) | Top-10 max (row) | Top-1 last row | Top-10 last row | mean last 10 rows (T1/T10) |')
p('|---|---|---|---|---|---|---|')
for name, a in arrays.items():
    p('| %s | %d | %.2f (%d) | %.2f (%d) | %.2f | %.2f | %.2f / %.2f |' % (
        name, a.shape[0], 100 * a[:, 0].max(), a[:, 0].argmax(), 100 * a[:, 1].max(), a[:, 1].argmax(),
        100 * a[-1, 0], 100 * a[-1, 1], 100 * a[-10:, 0].mean(), 100 * a[-10:, 1].mean()))
p()

# ---------------------------------------------------------------- (c) denominator inference
p('## (c) Inferred test-set size N (denominator)')
p()
allv = np.concatenate([a.ravel() for a in arrays.values()])
allv = allv[(allv > 0) & (allv < 1)]
cands = []
for N in range(1, 3000):
    k = np.round(allv * N)
    if np.all(np.abs(allv * N - k) < 1e-3 * N / 283 * 2.5):  # tolerance scaled; values are float64 so this is tight
        cands.append(N)
tight = []
for N in cands:
    err = np.abs(allv * N - np.round(allv * N)).max()
    tight.append((N, err))
p('Smallest N for which every stored accuracy equals k/N (|error| < 1e-6*N): ')
best = [(N, e) for N, e in tight if e < 1e-6 * N]
p('- candidates: %s' % (best[:5] if best else '未找到'))
if best:
    N0 = best[0][0]
    p('- N = %d; max |acc*N - round| = %.2e' % (N0, best[0][1]))
p()
p('Thesis Table 3.2 cells as k/283 (percent -> nearest k and the exact value):')
p()
p('| row | stage | Top-1 (%) | k/283 -> % | Top-10 (%) | k/283 -> % | consistent |')
p('|---|---|---|---|---|---|---|')
for row, cells in TABLE.items():
    for s, (t1, t10) in enumerate(cells, 1):
        k1 = round(t1 / 100 * 283); k10 = round(t10 / 100 * 283)
        v1 = 100 * k1 / 283; v10 = 100 * k10 / 283
        ok = abs(round(v1, 1) - t1) < 0.051 and abs(round(v10, 1) - t10) < 0.051
        p('| %s | S%d | %.1f | %d -> %.2f | %.1f | %d -> %.2f | %s |' % (row, s, t1, k1, v1, t10, k10, v10, 'yes' if ok else 'NO'))
p()

# ---------------------------------------------------------------- (d) match table to rows
p('## (d) Table 3.2 cells found in the stored curves (both Top-1 and Top-10 of a row match to 0.05 %)')
p()
for row, cells in TABLE.items():
    for s, (t1, t10) in enumerate(cells, 1):
        hits = []
        for name, a in arrays.items():
            r = np.where((np.abs(100 * a[:, 0] - t1) < 0.051) & (np.abs(100 * a[:, 1] - t10) < 0.051))[0]
            if len(r):
                hits.append('%s rows %s (epochs %s)' % (name, list(r), [int(x) * 3 + 1 for x in r]))
        p('- %s S%d (%.1f / %.1f): %s' % (row, s, t1, t10, '; '.join(hits) if hits else '未找到'))
p()
txt = '\n'.join(L)
print(txt)
with open(OUT, 'w') as fh:
    fh.write(txt + '\n')
print('written', OUT)
