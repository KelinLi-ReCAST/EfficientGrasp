#!/usr/bin/env python3
"""B4: count per-configuration gripper point-cloud files on disk.

Scans contact_point_selection/UniGrasp/data/gripper_features/Data_DB/<g>/ and
contact_point_selection/UniGrasp/data/grippers/<g>/ for files named
<prefix>_<int>.npy, reports counts / index ranges / gaps / array shapes, and
writes results/thesis_ch3/B4_gripper_config_counts.md.

Usage:  python3 evaluation/thesis_ch3/b4_gripper_config_counts.py
"""
import os, re, sys, collections
import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
UG = os.path.join(ROOT, 'contact_point_selection', 'UniGrasp', 'data')
DIRS = [os.path.join(UG, 'gripper_features', 'Data_DB'), os.path.join(UG, 'grippers')]
OUT = os.path.join(ROOT, 'results', 'thesis_ch3', 'B4_gripper_config_counts.md')

pat = re.compile(r'^(.*?)_(\d+)\.npy$')
lines = ['# B4 gripper configuration file counts', '',
         'Generated by `python3 evaluation/thesis_ch3/b4_gripper_config_counts.py`', '']
for top in DIRS:
    lines.append('## %s' % os.path.relpath(top, ROOT))
    lines.append('')
    lines.append('| gripper dir | indexed files | prefix | index min..max | missing indices | shapes (unique) | other files |')
    lines.append('|---|---|---|---|---|---|---|')
    for g in sorted(os.listdir(top)):
        gd = os.path.join(top, g)
        if not os.path.isdir(gd):
            continue
        files = sorted(os.listdir(gd))
        idx = collections.defaultdict(list)
        other = []
        for f in files:
            m = pat.match(f)
            if m:
                idx[m.group(1)].append(int(m.group(2)))
            else:
                other.append(f)
        if not idx:
            lines.append('| %s | 0 | - | - | - | - | %s |' % (g, ', '.join(other)))
            continue
        for prefix, ids in idx.items():
            ids = sorted(ids)
            missing = sorted(set(range(ids[0], ids[-1] + 1)) - set(ids))
            shapes = collections.Counter()
            for i in ids:
                try:
                    a = np.load(os.path.join(gd, '%s_%d.npy' % (prefix, i)), allow_pickle=True)
                    shapes[str(a.shape) + ' ' + str(a.dtype)] += 1
                except Exception as e:  # noqa
                    shapes['ERR:' + str(e)[:40]] += 1
            lines.append('| %s | %d | %s | %d..%d | %s | %s | %s |' % (
                g, len(ids), prefix, ids[0], ids[-1],
                (str(missing) if missing else 'none'),
                '; '.join('%s x%d' % (k, v) for k, v in shapes.items()),
                ', '.join(other)))
    lines.append('')
    # shapes of the aggregate files
    lines.append('Aggregate files (shape):')
    lines.append('')
    for g in sorted(os.listdir(top)):
        gd = os.path.join(top, g)
        if not os.path.isdir(gd):
            continue
        for f in sorted(os.listdir(gd)):
            if pat.match(f) or not f.endswith('.npy'):
                continue
            try:
                a = np.load(os.path.join(gd, f), allow_pickle=True)
                lines.append('- %s/%s: %s %s' % (g, f, a.shape, a.dtype))
            except Exception as e:  # noqa
                lines.append('- %s/%s: ERR %s' % (g, f, e))
    lines.append('')
txt = '\n'.join(lines)
print(txt)
with open(OUT, 'w') as fh:
    fh.write(txt + '\n')
print('written', OUT)
