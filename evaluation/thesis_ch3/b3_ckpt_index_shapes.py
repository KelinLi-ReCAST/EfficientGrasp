#!/usr/bin/env python3
"""B3/B2 helper: list variable names + shapes in a TF1 checkpoint .index file
without TensorFlow (parses the leveldb/SSTable format + BundleEntryProto).

Usage: python3 evaluation/thesis_ch3/b3_ckpt_index_shapes.py [ckpt.index ...]
Writes results/thesis_ch3/B3_ckpt_variables.md
"""
import os, sys, struct, glob, zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CKPT_DIR = os.path.join(ROOT, 'contact_point_selection', 'UniGrasp', 'saved_models', 'point_set_selection')
OUT = os.path.join(ROOT, 'results', 'thesis_ch3', 'B3_ckpt_variables.md')


def read_varint(buf, pos):
    result = 0; shift = 0
    while True:
        b = buf[pos]; pos += 1
        result |= (b & 0x7F) << shift
        if not (b & 0x80):
            return result, pos
        shift += 7


def parse_message(buf):
    pos = 0; out = []
    while pos < len(buf):
        key, pos = read_varint(buf, pos)
        fn, wt = key >> 3, key & 7
        if wt == 0:
            v, pos = read_varint(buf, pos)
        elif wt == 1:
            v = buf[pos:pos + 8]; pos += 8
        elif wt == 2:
            ln, pos = read_varint(buf, pos); v = buf[pos:pos + ln]; pos += ln
        elif wt == 5:
            v = buf[pos:pos + 4]; pos += 4
        else:
            raise ValueError(wt)
        out.append((fn, wt, v))
    return out


def read_block(data, offset, size):
    raw = data[offset:offset + size]
    ctype = data[offset + size]
    if ctype == 1:  # snappy
        import snappy  # noqa
        raw = snappy.uncompress(raw)
    elif ctype != 0:
        raise ValueError('unknown compression %d' % ctype)
    n_restarts = struct.unpack('<I', raw[-4:])[0]
    end = len(raw) - 4 - 4 * n_restarts
    pos = 0; key = b''; entries = []
    while pos < end:
        shared, pos = read_varint(raw, pos)
        unshared, pos = read_varint(raw, pos)
        vlen, pos = read_varint(raw, pos)
        key = key[:shared] + raw[pos:pos + unshared]; pos += unshared
        val = raw[pos:pos + vlen]; pos += vlen
        entries.append((key, val))
    return entries


def decode_handle(buf, pos=0):
    off, pos = read_varint(buf, pos)
    size, pos = read_varint(buf, pos)
    return off, size, pos


def list_variables(index_path):
    data = open(index_path, 'rb').read()
    footer = data[-48:]
    assert footer[-8:] == bytes.fromhex('57fb808b247547db'), 'bad table magic'
    moff, msize, p = decode_handle(footer, 0)
    ioff, isize, p = decode_handle(footer, p)
    index_entries = read_block(data, ioff, isize)
    out = []
    for _, handle in index_entries:
        boff, bsize, _ = decode_handle(handle, 0)
        for key, val in read_block(data, boff, bsize):
            if key == b'':
                continue  # header entry
            dtype = None; shape = []; size = None
            for fn, wt, v in parse_message(val):
                if fn == 1: dtype = v
                elif fn == 2:
                    for sfn, swt, sv in parse_message(v):
                        if sfn == 2:
                            for dfn, dwt, dv in parse_message(sv):
                                if dfn == 1: shape.append(dv)
                elif fn == 5: size = v
            out.append((key.decode('utf-8', 'replace'), dtype, shape, size))
    return out


def main():
    paths = sys.argv[1:] or sorted(glob.glob(os.path.join(CKPT_DIR, '*.index')))
    lines = ['# B3 checkpoint variable inventory', '',
             'Generated by `python3 evaluation/thesis_ch3/b3_ckpt_index_shapes.py` (SSTable/BundleEntryProto parser, no TensorFlow).', '']
    for p in paths:
        vs = list_variables(p)
        n_train = [v for v in vs if '/Adam' not in v[0] and 'beta1_power' not in v[0] and 'beta2_power' not in v[0]]
        n_params = sum((int.__mul__(*s) if len(s) == 2 else (s[0] if len(s) == 1 else (1 if not s else eval('*'.join(map(str, s)))))) for _, _, s, _ in n_train)
        lines.append('## %s' % os.path.relpath(p, ROOT))
        lines.append('')
        lines.append('- data file size: %d bytes' % os.path.getsize(p.replace('.index', '.data-00000-of-00001')))
        lines.append('- total entries: %d ; non-Adam variables: %d ; params in non-Adam variables: %d' % (len(vs), len(n_train), n_params))
        lines.append('- variables whose shape involves the gripper-feature input (first conv on extra_feat, and fa_layer0 input):')
        for name, dt, sh, sz in n_train:
            if ('/Conv1D' in name and '/W' in name) or 'fa_layer0/conv_0/weights' in name or 'fc1_3/weights' in name:
                lines.append('    - %s %s' % (name, sh))
        lines.append('- scopes (top two levels) and variable counts:')
        import collections
        c = collections.Counter('/'.join(n.split('/')[:2]) for n, _, _, _ in n_train)
        for k, v in sorted(c.items()):
            lines.append('    - %s: %d' % (k, v))
        lines.append('')
        lines.append('<details><summary>all non-Adam variables</summary>')
        lines.append('')
        for name, dt, sh, sz in n_train:
            lines.append('- %s %s' % (name, sh))
        lines.append('')
        lines.append('</details>')
        lines.append('')
    txt = '\n'.join(lines)
    print('\n'.join(l for l in lines if not l.startswith('- stage')))
    with open(OUT, 'w') as fh:
        fh.write(txt + '\n')
    print('written', OUT)


if __name__ == '__main__':
    main()
